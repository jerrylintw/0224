# 這個程式用來生成模擬的股票每日漲跌數據，使用numpy隨機生成常態分配的數據。
import numpy as np  # 引入numpy庫，用來處理數學運算和陣列

# 設定隨機種子，讓每次運行結果一樣，就像設定遊戲的種子一樣
np.random.seed(42)

# 生成30個隨機數，這些數代表每天股票的漲跌，像擲骰子決定漲跌多少
# 平均是0，意思是平均不漲不跌
# 標準差是2，意思是波動不大
# 30個數，代表30天
daily_changes = np.random.normal(loc=0, scale=2, size=30)

# 印出前5天的漲跌，讓我們看看數據長什麼樣子
print("每日漲跌幅（前 5 天）：", daily_changes[:5])
# 輸出範例：[ 0.99  -0.14   1.86  -0.38   1.10]